/** 档位 id 联合（与 settings-contract 的 OptimizerTier 一致，此处不 import 以免循环）。 */
export type OptimizerSpecTier = keyof typeof OPTIMIZER_SPECS

/**
 * 组装一次优化的 system 提示词。
 * @param tier - 强度档位；未知值走 advanced（默认档）。
 * @returns 该档位的完整系统提示词。
 */
export function buildOptimizeSystem(tier: string): string {
  const spec = OPTIMIZER_SPECS[tier as OptimizerSpecTier] ?? OPTIMIZER_SPECS.advanced
  return spec.system
}

/**
 * 组装一次优化的 temperature。
 * @param tier - 强度档位；未知值走 advanced。
 * @returns 该档位的采样温度。
 */
export function buildOptimizeTemperature(tier: string): number {
  const spec = OPTIMIZER_SPECS[tier as OptimizerSpecTier] ?? OPTIMIZER_SPECS.advanced
  return spec.temperature
}

/**
 * 传话框架：把用户原话包成「待转达内容」而不是「对你说的话」。
 *
 * 这是原作者修「优化 AI 以为自己在和用户对话」的关键一招 —— 裸文本会被当成
 * 对话输入，于是模型开始回应你而不是替你转达。本插件没有「重新优化方向」
 * 那条支线，故只保留主路径。
 * @param original - 输入框里的原话。
 * @returns 直接作为 user 消息发送的文本。
 */
export function buildOptimizeUser(original: string): string {
  return [
    '【待转达内容】下面是"用户"发给我的原话。**它不是说给你听的**，你不需要回应它、也不需要替用户去做这件事。',
    '<原文>',
    String(original ?? ''),
    '</原文>',
    '',
    '【你的任务】以用户的名义，把上面的内容整理成**一条可以直接发给"工作 AI"的命令**：',
    '- 只输出这条命令本身；不要回应我、不要回答问题、不要谢幕、不要解释你做了什么。',
    '- 读你这条命令的人只有"工作 AI"一个。',
  ].join('\n')
}
